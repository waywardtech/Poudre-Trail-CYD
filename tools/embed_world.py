#!/usr/bin/env python3
"""Bake data/*.csv and data/events/*.txt into include/world_data.hpp so the
firmware can run the full game with no SD card. Run after editing content:
    python3 tools/embed_world.py
"""
import os, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
data = os.path.join(root, "data")

def raw(name, text):
    assert ')WCSV"' not in text
    return f'static const char {name}[] = R"WCSV({text})WCSV";\n'

out = ["// GENERATED by tools/embed_world.py from data/ - do not edit by hand.\n",
       "#pragma once\n\n"]
for var, fn in (("WORLD_LOCATIONS_CSV", "locations.csv"),
                ("WORLD_EVENTS_CSV", "events.csv"),
                ("WORLD_TRADES_CSV", "trades.csv")):
    out.append(raw(var, open(os.path.join(data, fn), encoding="utf-8").read()))
out.append("\nstruct WorldBody { const char* path; const char* text; };\n")
out.append("static const WorldBody WORLD_BODIES[] = {\n")
evdir = os.path.join(data, "events")
for fn in sorted(os.listdir(evdir)):
    if not fn.endswith(".txt"):
        continue
    text = open(os.path.join(evdir, fn), encoding="utf-8").read()
    assert ')WCSV"' not in text
    out.append(f'    {{"events/{fn}", R"WCSV({text})WCSV"}},\n')
out.append("};\n")
open(os.path.join(root, "include", "world_data.hpp"), "w", encoding="utf-8").write("".join(out))
print("wrote include/world_data.hpp")
